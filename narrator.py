#!/usr/bin/env python3
"""The only part of Plain Q that leaves the machine.

Everything the page shows by default — the statevector, the Bloch vectors, the
entropy, the sentence under every box — is computed locally by Qiskit. Nothing
is generated by a model, so the numbers are always the true ones and the app
still works with no internet at all.

`narrator.py` adds one thing on top: a free-form follow-up question. When the
user types "why do these two wires have to agree?", we hand the circuit *and the
numbers Qiskit already computed* to an NVIDIA Nemotron model served by Nebius
Token Factory, and it writes back one short answer in plain language.

The model never computes quantum mechanics. It is given the answer and asked to
say it in English a beginner can follow. If no API key is configured we call
nothing and the tutor reports itself as offline — the rest of the app is
unaffected.
"""

import json
import os
import time
import urllib.error
import urllib.request
from pathlib import Path

DEFAULT_BASE = "https://api.tokenfactory.nebius.com/v1"
DEFAULT_MODEL = "nvidia/nemotron-3-super-120b-a12b"
TIMEOUT = 45

SYSTEM = """You are the tutor inside Plain Q, a quantum-circuit toy for absolute beginners.

The user built a tiny circuit and Qiskit has already computed every number exactly.
You are given that circuit and those numbers. Write one short answer, in plain words,
that a 15-year-old with no physics could follow.

Hard rules:
- Never invent a number or a probability. Use only the values given to you.
- 60 to 110 words. One flowing paragraph. No bullet lists, no headings, no markdown.
- The first time you use a technical word, define it in the same sentence
  (for example "entanglement, which means the two wires stop having answers of their own").
- Speak about *this* board, not about quantum computing in general.
- If the question is not about this circuit, say so in one sentence and then say
  what the board actually does.
- Answer in {language}, and nowhere else.
"""


def _read_dotenv():
    """Read .env / .env.local next to this file. No dependency, no side effects."""
    here = Path(__file__).resolve().parent
    found = {}
    for name in (".env", ".env.local"):
        path = here / name
        if not path.exists():
            continue
        try:
            text = path.read_text(encoding="utf-8")
        except OSError:
            continue
        for line in text.splitlines():
            line = line.strip()
            if not line or line.startswith("#") or "=" not in line:
                continue
            key, value = line.split("=", 1)
            found[key.strip()] = value.strip().strip('"').strip("'")
    return found


def config():
    dot = _read_dotenv()

    def pick(name, default=""):
        return (os.environ.get(name) or dot.get(name) or default).strip()

    return {
        "api_key": pick("NEBIUS_API_KEY"),
        "base_url": pick("NEBIUS_BASE_URL", DEFAULT_BASE).rstrip("/"),
        "model": pick("NEBIUS_MODEL", DEFAULT_MODEL),
    }


def describe_provider():
    """What the front end needs to know before it shows an input box."""
    cfg = config()
    return {
        "enabled": bool(cfg["api_key"]),
        "model": cfg["model"],
        "provider": "Nebius Token Factory",
        "endpoint": cfg["base_url"],
    }


def _brief(state):
    """The exact numbers, trimmed to what a tutor needs. Nothing is paraphrased here."""
    steps = [
        {"box": s["gate"], "wires": s["qubits"], "after": _dist(s["probs"], state["n"])}
        for s in state.get("steps", [])
    ]
    return {
        "wires": state.get("n"),
        "boxes_in_order": steps,
        "final_chance_of_each_answer": _dist(state.get("probs") or [], state.get("n")),
        "each_wire_bloch": [
            {"wire": i, "x": round(q["x"], 3), "y": round(q["y"], 3), "z": round(q["z"], 3),
             "length": round(q["r"], 3), "entropy_bits": round(q["entropy"], 3)}
            for i, q in enumerate(state.get("qubits") or [])
        ],
        "simulator": state.get("engine"),
    }


def _dist(probs, n):
    """Outcome labels in wire order A B C.

    Qiskit's statevector index is little-endian: index 1 with three wires is
    |q2 q1 q0⟩ = |001⟩, which the page calls "100" because wire A is q0 and is
    printed first. Reversing the binary string keeps the model's labels the same
    as the labels on screen, so it cannot say "01" while the page says "10".
    """
    out = {}
    width = n or 1
    for i, p in enumerate(probs):
        if p > 0.005:
            out[format(i, "0%db" % width)[::-1]] = round(p, 4)
    return out


def _text_of(message):
    """Find the prose in a chat-completion message.

    Nemotron may put the paragraph in `content`, or leave `content` null and
    write it to `reasoning_content` while it thinks. A null `content` used to
    hit `.strip()` and take the whole route down with an AttributeError; the
    user wants the sentence, so look in both places before giving up.
    """
    if not isinstance(message, dict):
        return ""
    for key in ("content", "reasoning_content", "reasoning"):
        value = message.get(key)
        if isinstance(value, str) and value.strip():
            return value.strip()
        if isinstance(value, list):
            parts = []
            for part in value:
                if isinstance(part, dict):
                    piece = part.get("text") or part.get("content")
                    if isinstance(piece, str) and piece.strip():
                        parts.append(piece.strip())
            if parts:
                return "".join(parts)
    return ""


def ask(question, state, lang="en"):
    """One question in, one paragraph out. Raises nothing — always returns a dict."""
    cfg = config()
    if not cfg["api_key"]:
        return {"ok": False, "reason": "no-key",
                "message": "No NEBIUS_API_KEY is configured, so the tutor is offline."}

    language = "Chinese (简体中文)" if str(lang).lower().startswith("zh") else "English"
    payload = {
        "model": cfg["model"],
        "temperature": 0.3,
        "max_tokens": 900,
        "messages": [
            {"role": "system", "content": SYSTEM.format(language=language)},
            {"role": "user", "content": json.dumps(
                {"circuit": _brief(state), "question": question}, ensure_ascii=False)},
        ],
    }

    req = urllib.request.Request(
        cfg["base_url"] + "/chat/completions",
        data=json.dumps(payload).encode("utf-8"),
        headers={
            "Content-Type": "application/json",
            "Authorization": "Bearer " + cfg["api_key"],
            "Accept": "application/json",
        },
        method="POST",
    )

    started = time.perf_counter()
    try:
        with urllib.request.urlopen(req, timeout=TIMEOUT) as resp:
            body = json.loads(resp.read().decode("utf-8"))
    except urllib.error.HTTPError as exc:
        detail = ""
        try:
            detail = exc.read().decode("utf-8", "replace")[:300]
        except Exception:  # noqa: BLE001
            pass
        reason = {401: "bad-key", 403: "bad-key", 429: "rate-limited"}.get(exc.code, "http-error")
        return {"ok": False, "reason": reason, "status": exc.code,
                "message": f"Nebius returned HTTP {exc.code}. {detail}".strip()}
    except urllib.error.URLError as exc:
        return {"ok": False, "reason": "unreachable", "message": f"Cannot reach Nebius: {exc.reason}"}
    except Exception as exc:  # noqa: BLE001
        return {"ok": False, "reason": "error", "message": f"{type(exc).__name__}: {exc}"}

    try:
        choice = (body.get("choices") or [{}])[0]
        message = choice.get("message") or {}
        text = _text_of(message)
        if not text:
            finish = choice.get("finish_reason")
            return {
                "ok": False,
                "reason": "empty-content",
                "message": (f"The model returned no text (finish_reason={finish}). "
                            f"Raw: {json.dumps(body)[:320]}"),
            }
    except Exception as exc:  # noqa: BLE001
        return {"ok": False, "reason": "bad-response",
                "message": f"{type(exc).__name__}: {exc}. Raw: {json.dumps(body)[:320]}"}

    usage = body.get("usage") or {}
    return {
        "ok": True,
        "text": text,
        "model": body.get("model") or cfg["model"],
        "provider": "Nebius Token Factory",
        "ms": round((time.perf_counter() - started) * 1000),
        "tokens": usage.get("total_tokens"),
    }
